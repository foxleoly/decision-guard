#!/usr/bin/env python3
"""Turn the audit log into TOML benchmark cases, and label them by hand.

    bench/label.py export [--limit N] [--db PATH] [--out DIR]   # log -> bench/cases/real-*.toml
    bench/label.py interactive [--dir DIR]                      # label unlabelled cases
    bench/label.py status [--dir DIR]                           # counts per file and class

The label is `p_destructive` (see docs/benchmark-rubric.md) and is only ever written by a
person. Nothing here guesses a label; a case starts with `label = ""` and the runner skips it.
"""

from __future__ import annotations

import argparse
import json
import re
import sqlite3
import sys
from pathlib import Path

# Commands that exist only because the deny list and the delete rule were being tested. They stay in the
# corpus (deleting evidence is worse than flagging it) but are marked so a report can separate them from
# real workflow.
PROBE = re.compile(
    r"\bmkfs\b|\bnewfs\b|diskutil\s+(erase|secureErase|partitionDisk|reformat|zeroDisk)"
    r"|\bdd\s+if=.*of=/dev/|:\s*\(\s*\)\s*\{|\brm -rf (\"?~\"?|\"?/\"?)(\s|$)"
    r"|\bprune -a|\brm -rf /tmp/dg-"
)
CASES = Path(__file__).resolve().parent / "cases"
SCHEMA = 1

# Lines that only exist because this tool was being developed; they would poison the sample.
NOISE = re.compile(r"decision-guard|\bDG=|sqlite3 -header|rust/scripts/build-dist|jq -c ")

# Secrets that must not land in a committed corpus.
SECRETS = [
    (re.compile(r"\b(sk-[A-Za-z0-9]{12,})"), "sk-REDACTED"),
    (re.compile(r"\b(ghp_[A-Za-z0-9]{20,})"), "ghp-REDACTED"),
    (re.compile(r"\b(github_pat_[A-Za-z0-9_]{20,})"), "github_pat-REDACTED"),
    (re.compile(r"(?i)\b(bearer)\s+[A-Za-z0-9._-]{12,}"), r"\1 REDACTED"),
    (re.compile(r"(?i)\b(api[_-]?key|token|password|passwd|secret|authorization)\b\s*[=:]\s*\S+"), r"\1=REDACTED"),
    (re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b"), "EMAIL-REDACTED"),
]


def sanitize(command: str) -> str:
    for pattern, repl in SECRETS:
        command = pattern.sub(repl, command)
    return command


def one_line(command: str) -> str:
    """TOML basic strings escape newlines anyway; collapsing keeps the corpus readable."""
    return " ".join(command.split())


def toml_str(value: str) -> str:
    # json.dumps emits the same escapes TOML's basic strings accept (and never escapes "/").
    return json.dumps(value, ensure_ascii=False)


def case_id(prefix: str, n: int) -> str:
    return f"{prefix}-{n:04d}"


def render(case: dict) -> str:
    keys = ["id", "category", "input_kind", "command", "cwd", "source", "bypass_class",
            "decided_stage", "decided_label", "label", "label_note"]
    lines = ["[[case]]"]
    for key in keys:
        value = case.get(key, "")
        if key == "label":
            # "0", "0.5" and "1" are numbers in the rubric, but a string is compared as text below.
            lines.append(f'{key} = {toml_str(str(value))}')
        else:
            lines.append(f"{key} = {toml_str(str(value))}")
    return "\n".join(lines)


def write_file(path: Path, cases: list[dict]) -> None:
    head = f"# Generated by bench/label.py; labels are written by a person only.\nschema_version = {SCHEMA}\n"
    body = "\n\n".join(render(c) for c in cases)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{head}\n{body}\n" if body else f"{head}\n")


def read_file(path: Path) -> list[dict]:
    import tomllib

    data = tomllib.loads(path.read_text())
    return data.get("case", [])


def all_files(directory: Path) -> list[Path]:
    return sorted(p for p in directory.glob("*.toml"))

def all_cases(directory: Path) -> list[tuple[Path, list[dict]]]:
    return [(p, read_file(p)) for p in all_files(directory)]


def cmd_export(args: argparse.Namespace) -> int:
    db = Path(args.db).expanduser()
    if not db.exists():
        print(f"no database at {db}", file=sys.stderr)
        return 1

    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    rows = con.execute(
        """
        SELECT command, cwd, choice, source, rule
        FROM decisions
        WHERE trim(command) <> ''
        ORDER BY id
        """
    ).fetchall()
    con.close()

    seen: set[str] = set()
    picked: dict[str, list[dict]] = {"destructive": [], "risky": [], "safe": [], "rule": []}
    for command, cwd, choice, source, rule in rows:
        text = one_line(command)
        if NOISE.search(text) or text in seen:
            continue
        seen.add(text)
        bucket = choice if choice in ("destructive", "risky", "safe") else "rule"
        picked[bucket].append(
            {
                "id": "",
                "category": f"log-{bucket}" if bucket != "rule" else f"log-rule-{rule or source}",
                "input_kind": "command",
                "command": sanitize(text),
                "cwd": cwd or "",
                "source": "probe" if PROBE.search(text) else "log",
                "bypass_class": "",
                "decided_stage": f"{source}:{rule}" if rule else source,
                "decided_label": choice or "",
                "label": "",
                "label_note": "",
            }
        )

    # Stratified: take the rare class first, then fill, so a small run still covers destructive.
    order = ["destructive", "risky", "safe", "rule"]
    quota = max(1, args.limit // len(order))
    out: list[dict] = []
    for bucket in order:
        out.extend(picked[bucket][:quota])
    if len(out) < args.limit:
        for bucket in order:
            out.extend(picked[bucket][quota:])
            if len(out) >= args.limit:
                break
    out = out[: args.limit]
    for n, case in enumerate(out, 1):
        case["id"] = case_id("real", n)

    path = Path(args.out) / "real-log.toml"
    write_file(path, out)
    print(f"wrote {len(out)} cases to {path}")
    for bucket in order:
        print(f"  available {bucket:<12} {len(picked[bucket]):>3}")
    return 0


def cmd_interactive(args: argparse.Namespace) -> int:
    directory = Path(args.dir)
    files = all_cases(directory)
    todo = [(path, case) for path, cases in files for case in cases if str(case.get("label", "")) == ""]
    if not todo:
        print("nothing unlabelled")
        return 0

    order = {"destructive": 0, "risky": 1, "safe": 2, "": 3}
    todo.sort(key=lambda pair: order.get(str(pair[1].get("decided_label", "")), 3))

    print(f"{len(todo)} unlabelled. 0 = safe, 0.5 = risky, 1 = destructive; ? = rubric, s = skip, q = quit.\n")
    rubric = (Path(__file__).resolve().parent.parent / "docs" / "benchmark-rubric.md")
    dirty: dict[Path, list[dict]] = {}

    blind = bool(getattr(args, "blind", False))
    if blind:
        print("blind mode: the guard's own verdict is hidden on high-risk cases (anti-anchoring).\n")

    for n, (path, case) in enumerate(todo, 1):
        cls = case.get("bypass_class") or ""
        high_risk = str(case.get("decided_label", "")) in ("destructive", "risky") or bool(cls)
        category = "" if (blind and high_risk) else case.get("category", "")
        print(f"[{n}/{len(todo)}] {case['id']}  {category}" + (f"  [{cls}]" if cls else ""))
        print(f"  cwd: {case.get('cwd','')}")
        text = str(case.get("command", ""))
        print("  " + (text if len(text) <= 300 else text[:300] + " …"))
        if not (blind and high_risk):
            print(f"  (the guard said: {case.get('decided_stage','?')} / {case.get('decided_label','-')})")
        while True:
            answer = input("  label> ").strip()
            if answer in ("0", "0.5", "1"):
                case["label"] = answer
                break
            if answer == "?":
                print(rubric.read_text() if rubric.exists() else "rubric missing")
                continue
            if answer == "s":
                break
            if answer == "q":
                for p, cases in dirty.items():
                    write_file(p, cases)
                print("saved")
                return 0
            print("  0, 0.5, 1, ? , s or q")
        if case.get("label", ""):
            dirty.setdefault(path, read_file(path))
            for stored in dirty[path]:
                if stored["id"] == case["id"]:
                    stored["label"] = case["label"]

    for p, cases in dirty.items():
        write_file(p, cases)
    print(f"labelled {sum(1 for _, c in todo if c.get('label',''))} of {len(todo)}")
    return 0


def cmd_set(args: argparse.Namespace) -> int:
    for path, cases in all_cases(Path(args.dir)):
        for case in cases:
            if case["id"] == args.case_id:
                case["label"] = args.label
                if args.note:
                    case["label_note"] = args.note
                write_file(path, cases)
                print(f"set {args.case_id} = {args.label}")
                return 0
    print(f"case {args.case_id} not found", file=sys.stderr)
    return 1


def cmd_status(args: argparse.Namespace) -> int:
    total = labelled = 0
    for path, cases in all_cases(Path(args.dir)):
        done = sum(1 for c in cases if str(c.get("label", "")) != "")
        total += len(cases)
        labelled += done
        print(f"{path.name:<28} {done:>3}/{len(cases):<3} labelled")
    if total:
        print(f"\n{labelled}/{total} labelled ({100 * labelled / total:.0f}%)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("export", help="audit log -> TOML cases")
    p.add_argument("--db", default="~/.decision-guard/decisions.db")
    p.add_argument("--limit", type=int, default=200)
    p.add_argument("--out", default=str(CASES))
    p.set_defaults(func=cmd_export)

    p = sub.add_parser("interactive", help="label unlabelled cases")
    p.add_argument("--dir", default=str(CASES))
    p.add_argument("--blind", action="store_true",
                   help="hide the guard's own verdict on high-risk cases (anti-anchoring)")
    p.set_defaults(func=cmd_interactive)

    p = sub.add_parser("set", help="set a label by case id (non-interactive)")
    p.add_argument("case_id")
    p.add_argument("label", choices=["0", "0.5", "1"])
    p.add_argument("note", nargs="?", default="")
    p.add_argument("--dir", default=str(CASES))
    p.set_defaults(func=cmd_set)

    p = sub.add_parser("status", help="counts")
    p.add_argument("--dir", default=str(CASES))
    p.set_defaults(func=cmd_status)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())

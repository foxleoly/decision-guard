#!/usr/bin/env python3
"""Run the full bench corpus against the d3-turbo service (vllm-sr cloud API).

Copies bench/run.py's mechanics, points the throwaway HOME's config.json at
d3turbo, and writes docs/benchmark-d3turbo.md. No code in the repo is touched.
"""
from __future__ import annotations

import contextlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
import run as bench  # bench/run.py as module

OUT = ROOT / "docs" / "benchmark-d3turbo.md"
SERVICE = "d3turbo"
API_KEY = "sk-vsr-2jfy4lBKYE6qvKeXKorOtVLIOJgsnss3g9hH01W4Ed5"


def make_d3_home() -> Path:
    home = bench.make_home()
    # Override active service in the copied config: d3turbo, plus the API key
    # (the key lives in this script, not in the user's config.json).
    cfg_path = home / ".decision-guard" / "config.json"
    cfg = json.loads(cfg_path.read_text())
    cfg["services"][SERVICE] = {
        "base_url": "https://decision.vllm-sr.ai/v1/systemone",
        "model": "vllm-sr/d3-turbo",
        "api_key": API_KEY,
        "timeout_ms": 30000,
        "budget_ms": 30000,
    }
    cfg["active"] = SERVICE
    cfg_path.write_text(json.dumps(cfg, indent=2))
    return home


def write_report(results: list[dict]) -> None:
    labelled = [c for c in results if str(c.get("label", "")) != ""]
    unlabelled = len(results) - len(labelled)
    pairs = [(float(c["label"]), c["p_destructive"]) for c in labelled if c.get("p_destructive") is not None]

    lines: list[str] = []
    lines.append("# Benchmark — d3-turbo (vllm-sr cloud API)\n")
    lines.append(
        f"Generated by `scripts/bench-d3turbo.py` (wrapper over `bench/run.py` mechanics) over "
        f"**{len(results)} cases** ({len(labelled)} labelled, {unlabelled} unlabelled), "
        f"service `{SERVICE}` -> https://decision.vllm-sr.ai, model `vllm-sr/d3-turbo`.\n"
    )
    lines.append(
        "Labels are human-written only; unlabelled cases report behaviour, not accuracy.\n"
    )

    # Stage attribution
    bench.stage_table(results, lines)

    decided_no_model = [c for c in results if c["stage"] in ("rule", "cache")]
    reached_model = [c for c in results if c["stage"] == "api"]
    errors = [c for c in results if c["stage"] in ("error", "no_service", "no_row")]
    lines.append(
        f"\nDecided without a model: **{len(decided_no_model)}/{len(results)}** "
        f"({100*len(decided_no_model)/max(len(results),1):.0f}%). "
        f"Reached d3-turbo: **{len(reached_model)}**. "
        f"Unjudged/errors: **{len(errors)}**.\n"
    )

    # Latency of the model calls
    if reached_model:
        lat = [c["latency_ms"] for c in reached_model if c.get("latency_ms")]
        lines.append("\n## d3-turbo model-call latency (ms)\n")
        lines.append("| n | P50 | P90 | P95 | P99 | max |")
        lines.append("|---|---|---|---|---|---|")
        lines.append(
            f"| {len(lat)} | {bench.percentile(lat,50):.0f} | {bench.percentile(lat,90):.0f} "
            f"| {bench.percentile(lat,95):.0f} | {bench.percentile(lat,99):.0f} | {max(lat):.0f} |"
        )

    # Accuracy at thresholds (labelled only)
    if pairs:
        lines.append("\n## Detection at each ask_p (labelled subset)\n")
        lines.append("| ask_p | precision | recall | TP | FP | FN | TN | Brier |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for ask in (0.3, 0.4, 0.5, 0.6, 0.7):
            m = bench.confusion(pairs, ask)
            lines.append(
                f"| {ask} | {bench.fmt(m['precision'])} | {bench.fmt(m['recall'])} | "
                f"{m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} | {bench.brier(pairs):.3f} |"
            )
        lines.append("\nBrier is a single value across the whole set (threshold-independent).\n")

    # Errors detail
    if errors:
        lines.append("## Unjudged / error rows\n")
        lines.append("| stage | n |")
        lines.append("|---|---|")
        from collections import Counter
        for stage, n in Counter(c["stage"] for c in errors).items():
            lines.append(f"| {stage} | {n} |")
        lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"report written to {OUT}")


def main() -> int:
    cases = bench.load_cases(bench.CASES)
    if not cases:
        print("no cases", file=sys.stderr)
        return 1
    if not bench.DG.exists():
        print(f"no binary at {bench.DG}", file=sys.stderr)
        return 1
    home = make_d3_home()
    print(f"running {len(cases)} cases against d3-turbo (HOME={home})", file=sys.stderr)
    results = bench.run_suite(cases, home, timeout=60.0)
    write_report(results)
    with contextlib.suppress(OSError):
        shutil.rmtree(home)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
